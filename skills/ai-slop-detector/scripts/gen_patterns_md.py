#!/usr/bin/env python3
"""Generate references/patterns.md from scripts/patterns.json. Stdlib only.

Usage: gen_patterns_md.py [--check]    (--check exits 1 if the file is out of date)
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "patterns.json")
DST = os.path.join(os.path.dirname(HERE), "references", "patterns.md")

ORDER = ["vocabulary", "filler", "opener", "closer", "contrast", "sycophancy", "signposting", "profundity", "structure"]
TITLES = {
    "vocabulary": "Clichéd vocabulary",
    "filler": "Filler and hedging",
    "opener": "Empty openers",
    "closer": "Empty closers and sign-offs",
    "contrast": "Contrast frames (\"not just X, it's Y\")",
    "sycophancy": "Sycophancy",
    "signposting": "Signposting",
    "profundity": "Fake-profound lines",
    "structure": "Formatting and structure",
}


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    with open(SRC, encoding="utf-8") as fh:
        pats = json.load(fh)["patterns"]
    out = [
        "# Pattern catalog",
        "",
        "<!-- Generated by scripts/gen_patterns_md.py from scripts/patterns.json. Edit the JSON, then re-run. -->",
        "",
        f"{len(pats)} patterns. Each hit adds its **weight** to the text's weighted total; single words weigh 0.3-1.5, "
        "stock phrases about 2, and structural frames 2-3, because one word proves little and a template proves more. "
        "Matching is per line and case-insensitive; when two patterns overlap on a line only the heavier one counts. "
        "A hit is a *style signal*, never evidence of who wrote the text.",
        "",
        "False-positive guards are built into the regexes: `robust` only matches generic praise (\"robust solution\"), "
        "not statistics (\"robust standard errors\"); `leverage` skips \"financial/operating leverage\"; `landscape` only "
        "matches figurative uses (\"the digital landscape\"); `foster` skips \"foster care\"; `elevate` skips \"elevated levels\".",
        "",
    ]
    by_cat: dict[str, list[dict]] = {}
    for p in pats:
        by_cat.setdefault(p["category"], []).append(p)
    for cat in ORDER + sorted(set(by_cat) - set(ORDER)):
        if cat not in by_cat:
            continue
        out += [f"## {TITLES.get(cat, cat.title())}", "", "| id | weight | example | why it reads as AI | try instead |", "|---|---:|---|---|---|"]
        for p in by_cat[cat]:
            out.append(f"| `{p['id']}` | {p['weight']:g} | {cell(p.get('example', ''))} | {cell(p['why'])} | {cell(p['instead'])} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        try:
            with open(DST, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = ""
        if current != text:
            print("references/patterns.md is out of date: run scripts/gen_patterns_md.py", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(DST)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
