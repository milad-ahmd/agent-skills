#!/usr/bin/env python3
"""Tests for valuation.py (stdlib unittest, no network).

Run: python3 -m unittest discover -s skills/codebase-valuation/scripts -p 'test_*.py'
Covers the line classifier, language detection, skip rules, the COCOMO arithmetic, git file listing and
history (in throwaway repos with an empty global config), the outputs' caveat, and exit codes.
"""
import json
import os
import subprocess
import sys
import tempfile
import unittest
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import valuation as v  # noqa: E402

SCRIPT = os.path.join(HERE, "valuation.py")
ENV = dict(os.environ, GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1", LC_ALL="C")
for k in ("GIT_DIR", "GIT_WORK_TREE"):
    ENV.pop(k, None)


def run(*args):
    r = subprocess.run([sys.executable, SCRIPT, *args], env=ENV, capture_output=True, text=True, timeout=60)
    return r.returncode, r.stdout, r.stderr


def write(root, name, text):
    full = os.path.join(root, name)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as fh:
        fh.write(text)


def commit(root, who, email, date, msg="change"):
    env = dict(ENV, GIT_AUTHOR_NAME=who, GIT_AUTHOR_EMAIL=email, GIT_COMMITTER_NAME=who,
               GIT_COMMITTER_EMAIL=email, GIT_AUTHOR_DATE=date, GIT_COMMITTER_DATE=date)
    for args in (["add", "-A"], ["commit", "-q", "--allow-empty", "-m", msg]):
        subprocess.run(["git", *args], cwd=root, env=env, check=True, capture_output=True)


def counts(text, lang):
    c = v.count_text(text, lang)
    return c["code"], c["comment"], c["blank"]


class TestClassify(unittest.TestCase):
    def test_c_like_lines(self):
        src = "// header\nint x = 1; // trailing\n\n/* one-line block */\nreturn x;\n"
        self.assertEqual(counts(src, "C"), (2, 2, 1))

    def test_multiline_block_and_blank_inside_counts_as_comment(self):
        src = "/*\n * doc\n\n */\nfoo();\n"
        self.assertEqual(counts(src, "Java"), (1, 4, 0))

    def test_code_after_block_end_is_code(self):
        self.assertEqual(counts("/* a\n b */ x = 1;\n", "JavaScript"), (1, 1, 0))

    def test_comment_tokens_inside_strings_are_code(self):
        src = 'url = "http://example.com"; /* not closed in string "*/" */\ns = "/*";\nnext();\n'
        self.assertEqual(counts(src, "JavaScript"), (3, 0, 0))

    def test_escaped_quote_in_string(self):
        self.assertEqual(counts('s = "a \\" // b";\n', "C"), (1, 0, 0))

    def test_python_hash_and_shebang(self):
        src = "#!/usr/bin/env python3\n# comment\nx = '#not'\n\n"
        self.assertEqual(counts(src, "Python"), (1, 2, 1))

    def test_html_and_lua_blocks(self):
        self.assertEqual(counts("<!-- a\nb -->\n<p>hi</p>\n", "HTML"), (1, 2, 0))
        self.assertEqual(counts("--[[ a\nb ]]\n-- c\nprint(1)\n", "Lua"), (1, 3, 0))

    def test_rust_lifetimes_do_not_open_strings(self):
        self.assertEqual(counts("fn f<'a>(x: &'a str) {} // note\n", "Rust"), (1, 0, 0))


class TestDetection(unittest.TestCase):
    def test_language_by_extension_filename_and_shebang(self):
        self.assertEqual(v.language("src/app.tsx"), "TypeScript")
        self.assertEqual(v.language("docker/Dockerfile"), "Dockerfile")
        self.assertEqual(v.language("bin/run", "#!/usr/bin/env bash"), "Shell")
        self.assertEqual(v.language("bin/tool", "#!/usr/bin/python3.11"), "Python")
        self.assertIsNone(v.language("notes"))
        self.assertIsNone(v.language("image.png"))

    def test_skip_reasons(self):
        self.assertEqual(v.skip_reason("web/package-lock.json"), "lockfile")
        self.assertEqual(v.skip_reason("vendor/github.com/x/y.go"), "vendored or build output")
        self.assertEqual(v.skip_reason("static/app.min.js"), "minified or generated")
        self.assertEqual(v.skip_reason("api/svc.pb.go"), "minified or generated")
        self.assertEqual(v.skip_reason("README.md"), "docs or data")
        self.assertIsNone(v.skip_reason("src/build_tools.py"))

    def test_generated_header(self):
        self.assertTrue(v.looks_generated("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x"))
        self.assertTrue(v.looks_generated("/* @generated */"))
        self.assertFalse(v.looks_generated("package main"))


class TestCocomo(unittest.TestCase):
    def test_ten_kloc_matches_the_formulas(self):
        e = v.cocomo(10000, 56286, 2.4)
        effort = 2.4 * 10 ** 1.05
        schedule = 2.5 * effort ** 0.38
        self.assertAlmostEqual(e["effort_person_months"], round(effort, 2))
        self.assertAlmostEqual(e["schedule_months"], round(schedule, 2))
        self.assertAlmostEqual(e["people"], round(effort / schedule, 2))
        self.assertEqual(e["cost"], round(effort / 12 * 56286 * 2.4))
        self.assertAlmostEqual(effort, 26.93, places=2)  # 2.4 x 10^1.05

    def test_zero_lines(self):
        self.assertEqual(v.cocomo(0, 56286, 2.4)["cost"], 0)

    def test_cost_scales_with_salary_and_overhead(self):
        base = v.cocomo(5000, 50000, 1.0)["cost"]
        self.assertAlmostEqual(v.cocomo(5000, 100000, 2.0)["cost"], base * 4, delta=2)


class TempDir(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = os.path.join(self._tmp.name, "proj")
        os.makedirs(self.root)

    def tearDown(self):
        self._tmp.cleanup()


class TestPlainDirectory(TempDir):
    def test_walk_skips_vendored_docs_and_minified(self):
        write(self.root, "main.go", "package main\n\n// entry\nfunc main() {}\n")
        write(self.root, "node_modules/x/index.js", "module.exports = 1\n")
        write(self.root, "README.md", "# hi\n")
        write(self.root, "web/app.js", "x=1;" * 400 + "\n")
        data = v.valuate(self.root)
        self.assertEqual(data["file_source"], "directory walk")
        self.assertEqual([r["language"] for r in data["languages"]], ["Go"])
        self.assertEqual(data["totals"]["code"], 2)
        self.assertEqual(data["skipped"], {"docs or data": 1, "minified or generated": 1})
        self.assertIsNone(data["git"])


class TestGitRepo(TempDir):
    def setUp(self):
        super().setUp()
        subprocess.run(["git", "init", "-q", "-b", "main"], cwd=self.root, env=ENV, check=True)
        write(self.root, ".gitignore", "secret_build/\n")
        write(self.root, "app.py", "import os\n\n# say hi\nprint('hi')\n")
        commit(self.root, "Ada", "ada@example.com", "2025-01-10T12:00:00Z")
        write(self.root, "lib.py", "def f():\n    return 1\n")
        commit(self.root, "Bob", "bob@example.com", "2025-07-10T12:00:00Z")
        commit(self.root, "Ada", "ADA@example.com", "2025-04-01T12:00:00Z")
        write(self.root, "secret_build/out.py", "x = 1\n" * 50)  # ignored
        write(self.root, "scratch.py", "y = 2\n" * 50)  # untracked

    def test_only_tracked_files_are_counted(self):
        data = v.valuate(self.root)
        self.assertEqual(data["file_source"], "git ls-files")
        self.assertEqual(data["totals"], {"files": 2, "code": 4, "comment": 1, "blank": 1})

    def test_history_counts_authors_without_names(self):
        g = v.valuate(self.root)["git"]
        self.assertEqual(g["commits"], 3)
        self.assertEqual(g["authors"], 2)  # email match is case-insensitive
        self.assertEqual((g["first_commit"], g["last_commit"]), ("2025-01-10", "2025-07-10"))
        self.assertAlmostEqual(g["span_months"], 5.9, places=1)
        self.assertNotIn("author_list", g)
        code, out, _ = run("-C", self.root)
        self.assertEqual(code, 0)
        self.assertNotIn("Ada", out)
        self.assertIn("2 authors, 3 commits over 5.9 months", out)

    def test_subdirectory_counts_only_its_files_and_commits(self):
        write(self.root, "svc/api.go", "package api\n")
        commit(self.root, "Cy", "cy@example.com", "2025-09-01T12:00:00Z")
        data = v.valuate(os.path.join(self.root, "svc"))
        self.assertEqual(data["totals"]["files"], 1)
        self.assertEqual((data["git"]["commits"], data["git"]["authors"]), (1, 1))

    def test_show_authors_lists_names(self):
        code, out, _ = run("-C", self.root, "--json", "--show-authors")
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(out)["git"]["author_list"],
                         [{"name": "Ada", "commits": 2}, {"name": "Bob", "commits": 1}])


class TestCli(TempDir):
    def test_every_output_carries_the_caveat_and_svg_is_valid(self):
        write(self.root, "a.c", "int main(void) { return 0; }\n")
        svg = os.path.join(self._tmp.name, "card.svg")
        code, out, _ = run("-C", self.root, "--svg", svg)
        self.assertEqual(code, 0)
        self.assertIn(v.CAVEAT, out)
        self.assertIn(v.CAVEAT, json.loads(run("-C", self.root, "--json")[1])["caveat"])
        with open(svg) as fh:
            body = fh.read()
        ET.fromstring(body)
        self.assertIn("1981 model estimate", body)
        self.assertIn("no git history", body)

    def test_custom_salary_and_currency(self):
        write(self.root, "a.c", "int x;\n" * 2000)
        code, out, _ = run("-C", self.root, "--json", "--salary", "70000", "--overhead", "1.5",
                           "--currency", "eur")
        data = json.loads(out)
        self.assertEqual(code, 0)
        self.assertEqual(data["model"]["currency"], "EUR")
        self.assertEqual(data["estimate"]["cost"], v.cocomo(2000, 70000, 1.5)["cost"])

    def test_no_code_exits_2(self):
        write(self.root, "README.md", "# docs only\n")
        code, _, err = run("-C", self.root)
        self.assertEqual(code, 2)
        self.assertIn("No code found", err)

    def test_bad_arguments_exit_2(self):
        write(self.root, "a.c", "int x;\n")
        self.assertEqual(run("-C", self.root, "--salary", "-5")[0], 2)
        self.assertEqual(run("-C", self.root, "--overhead", "0")[0], 2)
        self.assertEqual(run("-C", self.root, "--currency", "EUR")[0], 2)  # needs --salary in EUR
        self.assertEqual(run("-C", os.path.join(self.root, "missing"))[0], 2)

    def test_unwritable_svg_exits_2(self):
        write(self.root, "a.c", "int x;\n")
        self.assertEqual(run("-C", self.root, "--svg", os.path.join(self.root, "no", "dir", "c.svg"))[0], 2)


if __name__ == "__main__":
    unittest.main()
